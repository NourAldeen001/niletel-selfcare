CREATE TABLE TARIFF_PLAN (
    TARIFF_CODE CHAR(5) NOT NULL,
    TARIFF_NAME VARCHAR(40) NOT NULL,
    RATE_PER_MIN_PIASTERS INTEGER NOT NULL
        CHECK(RATE_PER_MIN_PIASTERS >= 0),
    ACTIVE_FLAG CHAR(1) NOT NULL
        CHECK(ACTIVE_FLAG IN ('Y', 'N')),

    CONSTRAINT PK_TARIFF_PLAN PRIMARY KEY(TARIFF_CODE)
);

CREATE TABLE OPERATOR (
    USERNAME VARCHAR(30) NOT NULL
        CHECK(LENGTH(USERNAME) BETWEEN 3 AND 30),
    PASSWORD_HASH CHAR(64) NOT NULL
        CHECK(PASSWORD_HASH ~ '^[0-9a-f]{64}$'),
    FULL_NAME VARCHAR(80) NOT NULL,
    ROLE_CODE CHAR(3) NOT NULL
        CHECK(ROLE_CODE IN ('OPR', 'SYS')),
    ACTIVE_FLAG CHAR(1) NOT NULL
        CHECK(ACTIVE_FLAG IN ('Y', 'N')),

    CONSTRAINT PK_OPERATOR PRIMARY KEY(USERNAME)
);

CREATE TABLE SUBSCRIBER(
    MSISDN CHAR(11) NOT NULL
        CHECK(MSISDN ~ '^01[0125][0-9]{8}$'),
    FULL_NAME VARCHAR(80) NOT NULL,
    PIN_HASH CHAR(64) NOT NULL
        CHECK(PIN_HASH ~ '^[0-9a-f]{64}$'),
    STATUS CHAR(1) NOT NULL
        CHECK(STATUS IN ('A', 'S')),
    TARIFF_CODE CHAR(5) NOT NULL,
    BALANCE_PIASTERS BIGINT NOT NULL
        CHECK(BALANCE_PIASTERS >= 0),
    ACTIVATION_DT DATE NOT NULL,

    CONSTRAINT PK_SUBSCRIBER PRIMARY KEY(MSISDN),
    CONSTRAINT FK_SUBSCRIBER_TARIFF FOREIGN KEY(TARIFF_CODE)
        REFERENCES TARIFF_PLAN(TARIFF_CODE)
);

CREATE TABLE LEDGER (
    TXN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    MSISDN CHAR(11) NOT NULL,
    TXN_TS TIMESTAMP NOT NULL,
    TXN_TYPE CHAR(1) NOT NULL
        CHECK(TXN_TYPE IN('R', 'D', 'F')),
    AMOUNT_PIASTERS BIGINT NOT NULL
        CHECK(AMOUNT_PIASTERS > 0),
    BALANCE_AFTER BIGINT NOT NULL
        CHECK(BALANCE_AFTER >= 0),
    REF_NO VARCHAR(20) NOT NULL DEFAULT '',
    REASON VARCHAR(100) NOT NULL
        CHECK(LENGTH(REASON) BETWEEN 1 AND 100),

    CONSTRAINT PK_LEDGER PRIMARY KEY(TXN_ID),
    CONSTRAINT FK_LEDGER_SUBSCRIBER FOREIGN KEY(MSISDN)
        REFERENCES SUBSCRIBER(MSISDN),
    CONSTRAINT CK_LEDGER_DEBIT_REFNO CHECK(
        TXN_TYPE <> 'D' OR REF_NO ~ '^[A-Z0-9-]{6,20}$'
    )
);

CREATE UNIQUE INDEX UQ_LEDGER_DEBIT_REFNO
    ON LEDGER(REF_NO) WHERE TXN_TYPE = 'D';

CREATE UNIQUE INDEX UQ_LEDGER_REFUND_REFNO
    ON LEDGER(REF_NO) WHERE TXN_TYPE = 'F';

CREATE INDEX IX_LEDGER_HISTORY
    ON LEDGER(MSISDN, TXN_TS DESC, TXN_ID DESC);

CREATE TABLE VOUCHER (
    CODE CHAR(14) NOT NULL
        CHECK(CODE ~ '^[0-9]{14}$'),
    VALUE_PIASTERS BIGINT NOT NULL
        CHECK(VALUE_PIASTERS > 0),
    USED_BY CHAR(11) NULL,
    USED_AT TIMESTAMP NULL,
    CREATED_BY VARCHAR(30) NOT NULL,
    CREATED_AT TIMESTAMP NOT NULL,

    CONSTRAINT PK_VOUCHER PRIMARY KEY(CODE),
    CONSTRAINT FK_VOUCHER_SUBSCRIBER FOREIGN KEY(USED_BY)
        REFERENCES SUBSCRIBER(MSISDN),
    CONSTRAINT FK_VOUCHER_OPERATOR FOREIGN KEY(CREATED_BY)
        REFERENCES OPERATOR(USERNAME),
    CONSTRAINT CK_VOUCHER_USED CHECK(
        (USED_BY IS NULL) = (USED_AT IS NULL)
    )
);

CREATE TABLE SMS_LOG(
    SMS_ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    MSISDN CHAR(11) NOT NULL,
    SMS_TEXT VARCHAR(160) NOT NULL,
    SENT_AT TIMESTAMP NOT NULL,
    TXN_ID BIGINT NOT NULL,

    CONSTRAINT PK_SMS_LOG PRIMARY KEY(SMS_ID),
    CONSTRAINT UQ_SMS_LOG_TXN UNIQUE(TXN_ID),
    CONSTRAINT FK_SMS_LOG_SUBSCRIBER FOREIGN KEY(MSISDN)
        REFERENCES SUBSCRIBER(MSISDN),
    CONSTRAINT FK_SMS_LOG_LEDGER FOREIGN KEY(TXN_ID)
        REFERENCES LEDGER(TXN_ID)
);